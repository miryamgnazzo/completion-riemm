function gen_boxplot_tex_EX1(matfile, texfile)
%GEN_BOXPLOT_TEX_EX1  Build the pgfplots box-plot fragment for Case study 1.
%   Reads case1_robustness_seed50_results.mat and writes a tikzpicture with,
%   for every d, two side-by-side boxes: Riemannian completion and ACA.
%   Quartiles and Tukey whiskers (1.5*IQR) are computed in log10 scale, so
%   the spread is multiplicative, and converted back to 10^().
%
%   gen_boxplot_tex_EX1
%   gen_boxplot_tex_EX1('other.mat', 'out.tex')
%
%   Output: case1_robustness_boxplot_50.tex

here = fileparts(mfilename('fullpath'));
if nargin < 1 || isempty(matfile), matfile = 'case1_robustness_seed50_results.mat'; end
if nargin < 2 || isempty(texfile), texfile = 'case1_robustness_boxplot_50.tex'; end
if ~isAbsPath(matfile), matfile = fullfile(here, matfile); end
if ~isAbsPath(texfile), texfile = fullfile(here, texfile); end

S = load(matfile);
p_list = S.p_list(:).';            % free parameters, without time
d_list = p_list + 1;               % tensor order, the axis used in the paper
np = numel(p_list);

methods = {'cr_L2', 'aca_L2'};
labels  = {'Riemannian', 'ACA'};
colors  = {'chebblue', 'acaorange'};
offset  = [-0.18, +0.18];
boxext  = 0.28;

fid = fopen(texfile, 'w');
assert(fid > 0, 'cannot open %s for writing', texfile);

fprintf(fid, '%% Compile as standalone, or \\input it into a document.\n');
fprintf(fid, '%% Required preamble:\n');
fprintf(fid, '%%   \\usepackage{pgfplots}\\pgfplotsset{compat=1.16}\n');
fprintf(fid, '%%   \\usepgfplotslibrary{statistics}\n');
fprintf(fid, '%%\n');
fprintf(fid, '%% Generated by gen_boxplot_tex_EX1.m from %s (%d seeds, d = %s, N = %d).\n', ...
        matfileName(matfile), S.nseeds, strjoin(compose('%d', d_list), ','), S.ncheb(end));
fprintf(fid, '%% Quartiles and Tukey whiskers (1.5*IQR) computed in log10 scale,\n');
fprintf(fid, '%% then converted back.\n');
fprintf(fid, '\\definecolor{chebblue}{RGB}{0,115,189}\n');
fprintf(fid, '\\definecolor{acaorange}{RGB}{217,83,25}\n\n');

fprintf(fid, '\\begin{tikzpicture}\n');
fprintf(fid, '\\begin{axis}[\n');
fprintf(fid, '    boxplot/draw direction=y,\n');
fprintf(fid, '    ymode=log,\n');
fprintf(fid, '    width=\\linewidth, height=5.2cm,       %% fits one IEEE column (~8.8cm)\n');
fprintf(fid, '    xtick={%s},\n',       strjoin(compose('%d', p_list), ','));
fprintf(fid, '    xticklabels={%s},\n', strjoin(compose('%d', d_list), ','));
fprintf(fid, '    xlabel={$d$},\n');
fprintf(fid, '    ylabel={Accuracy},\n');
fprintf(fid, '    xmin=%g, xmax=%g,\n', p_list(1)-0.6, p_list(end)+0.6);
fprintf(fid, '    ymajorgrids, major grid style={gray!25},\n');
fprintf(fid, '    tick label style={font=\\footnotesize},\n');
fprintf(fid, '    label style={font=\\footnotesize},\n');
fprintf(fid, ['    legend style={at={(0.02,0.98)}, anchor=north west, font=\\scriptsize,\n' ...
              '                  draw=none, fill=white, fill opacity=0.6, text opacity=1,\n' ...
              '                  row sep=-1pt, inner sep=1.5pt},\n']);
fprintf(fid, '    legend cell align=left,\n');
fprintf(fid, '    boxplot={box extend=%.2f},\n', boxext);
fprintf(fid, '    mark size=1.2pt,\n');
fprintf(fid, '    line width=0.6pt,\n');
fprintf(fid, ']\n\n');

for m = 1:numel(methods)
    fprintf(fid, '\\addlegendimage{area legend, fill=%s!35, draw=%s}\n', colors{m}, colors{m});
end

for m = 1:numel(methods)
    M = S.(methods{m});                          % nseeds x np
    for ip = 1:np
        data = M(:, ip);
        data = data(isfinite(data) & data > 0);
        [lw, q1, med, q3, uw, out] = box_stats_log(data);
        xpos = p_list(ip) + offset(m);

        if isempty(out)
            coordstr = '';
        else
            coordstr = strjoin(compose('(0,%.6g)', sort(out(:)).'), ' ');
        end

        fprintf(fid, ['\\addplot+[%s, fill=%s!35, solid, mark=o, ' ...
            'boxplot prepared={draw position=%.3f, box extend=%.3f, ' ...
            'lower whisker=%.6g, lower quartile=%.6g, median=%.6g, ' ...
            'upper quartile=%.6g, upper whisker=%.6g}] coordinates {%s};\n'], ...
            colors{m}, colors{m}, xpos, boxext, lw, q1, med, q3, uw, coordstr);
    end
    fprintf(fid, '\n');
end

fprintf(fid, '\\legend{%s}\n', strjoin(labels, ','));
fprintf(fid, '\\end{axis}\n');
fprintf(fid, '\\end{tikzpicture}\n');
fclose(fid);

fprintf('Written %s (%d values of d, %d seeds).\n', texfile, np, S.nseeds);
end

%% ---- Tukey statistics in log10 scale
function [lw, q1, med, q3, uw, outliers] = box_stats_log(x)
    l    = log10(x(:));
    q1l  = prctile(l, 25);
    medl = median(l);
    q3l  = prctile(l, 75);
    iqrl = q3l - q1l;
    lf   = q1l - 1.5*iqrl;   uf = q3l + 1.5*iqrl;
    inl  = l(l >= lf & l <= uf);
    lwl  = min(inl);         uwl = max(inl);
    outl = l(l < lf | l > uf);
    q1 = 10^q1l;  med = 10^medl;  q3 = 10^q3l;
    lw = 10^lwl;  uw  = 10^uwl;
    outliers = 10.^outl;
end

function n = matfileName(p)
    [~, b, e] = fileparts(p);
    n = [b e];
end

function tf = isAbsPath(p)
    tf = ~isempty(regexp(p, '^([A-Za-z]:[\\/]|[\\/])', 'once'));
end
