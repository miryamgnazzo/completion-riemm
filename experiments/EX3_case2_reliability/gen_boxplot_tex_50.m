%% gen_boxplot_tex_50
% Build the pgfplots box-plot fragments for Case study 2 from the stored
% .mat files (d = 5,6,7 by ne = 20,30,40). Statistics are quartiles and
% Tukey whiskers computed on the raw data; log10 is applied only to the
% plotted values.
%
% Output: dof_plots.tex, time_plots.tex, dof_plots_log.tex,
% time_plots_log.tex, summary_stats.txt

here = fileparts(mfilename('fullpath'));
d_want  = [5 6 7];
ne_want = [20 30 40];

srcs = { 'case2_compare_reliability_seed50_d567_ne20.mat'
         'case2_compare_reliability_seed50_d567_ne30.mat'
         'case2_compare_reliability_seed50_d567_ne40.mat' };

R = containers.Map('KeyType','char','ValueType','any');
for k = 1:numel(srcs)
    f = fullfile(here, srcs{k});
    if ~isfile(f), warning('manca %s', srcs{k}); continue; end
    S = load(f);
    Nt = S.Nt; Np = S.Np; rt = S.rank_time; rp = S.rank_par; nseed = numel(S.seed_list);
    for id = 1:numel(S.d_list)
        d = S.d_list(id);
        R(sprintf('d%d_ne%d', d, S.ne)) = struct( ...
            'rk', S.aca_rk(:,id), 'at', S.aca_t(:,id), 'ct', S.che_t(:,id));
    end
end

G = struct('name',{},'dof_c',{},'dof_a',{},'t_c',{},'t_a',{});
for d = d_want
    dof_cheb_d = rt*rp^(d-1) + Nt*rt + (d-1)*Np*rp;   % costante (rango fisso)
    for ne = ne_want
        key = sprintf('d%d_ne%d', d, ne);
        if ~isKey(R,key), warning('manca %s', key); continue; end
        s = R(key);
        G(end+1) = struct('name', key, ...
            'dof_c', repmat(dof_cheb_d, numel(s.rk), 1), ...
            'dof_a', s.rk * (Nt + (d-1)*Np), ...
            't_c', s.ct, 't_a', s.at); %#ok<SAGROW>
    end
end
ng = numel(G);

emit(fullfile(here,'dof_plots.tex'),      G, 'dof_c', 'dof_a', 'raw');
emit(fullfile(here,'time_plots.tex'),     G, 't_c',   't_a',   'raw');
emit(fullfile(here,'dof_plots_log.tex'),  G, 'dof_c', 'dof_a', 'log');
emit(fullfile(here,'time_plots_log.tex'), G, 't_c',   't_a',   'log');

% ---- riepilogo + estremi per gli assi --------------------------------------
fid = fopen(fullfile(here,'summary_stats.txt'),'w');
fprintf(fid,'Nt=%d Np=%d rank_time=%d rank_par=%d (%d seeds)\n\n', Nt,Np,rt,rp,nseed);
fprintf(fid,'%-9s | %8s | %-22s | %8s | %-22s\n','group','dofCheb', ...
    'dofACA med [min-max]','tCheb med','tACA med [min-max]');
for i=1:ng
    fprintf(fid,'%-9s | %8d | %6.0f [%5d-%5d] | %8.1f | %6.1f [%5.1f-%5.1f]\n', ...
        G(i).name, G(i).dof_c(1), median(G(i).dof_a), min(G(i).dof_a), max(G(i).dof_a), ...
        median(G(i).t_c), median(G(i).t_a), min(G(i).t_a), max(G(i).t_a));
end
fclose(fid);
type(fullfile(here,'summary_stats.txt'));

% actual plotted extremes (whiskers AND outliers), to set ymin/ymax
fprintf('\n=== log10 EXTREMES TO BE PLOTTED (for ymin/ymax) ===\n');
for pair = {{'dof_c','dof_a','DoF'}, {'t_c','t_a','Time'}}
    fc = pair{1}{1}; fa = pair{1}{2}; nm = pair{1}{3};
    lo = inf; hi = -inf;
    for i=1:ng
        for fld = {fc, fa}
            st = bstats(G(i).(fld{1}));
            v = [st.lw, st.uw, st.out(:).'];
            lo = min(lo, min(log10(v))); hi = max(hi, max(log10(v)));
        end
    end
    fprintf('%-5s: log10 in [%.3f, %.3f]  -> values [%.1f, %.1f]  (suggested ymin=%.2f ymax=%.2f)\n', ...
        nm, lo, hi, 10^lo, 10^hi, lo-0.08, hi+0.08);
end

%% ===== local functions =====================================================
function emit(fname, G, fc, fa, mode)
    uselog = strcmpi(mode, 'log');
    if uselog, tr = @(v) log10(v); else, tr = @(v) v; end
    fid = fopen(fname,'w');
    fprintf(fid, '%% generated by gen_boxplot_tex_50.m -- do not edit by hand\n');
    if uselog
        fprintf(fid, ['%% Statistics computed on the raw data; log10 is applied\n' ...
                      '%% ONLY to the resulting statistics, for plotting.\n' ...
                      '%% (= "box-plot of the raw data shown on a logarithmic axis")\n']);
    else
        fprintf(fid, '%% Statistics and plot on the raw data (linear axis).\n');
    end
    for meth = 1:2
        if meth==1, fld=fc; sty='chebstyle'; off=-0.19;
        else,       fld=fa; sty='acastyle';  off=+0.19;
        end
        for i = 1:numel(G)
            st = bstats(G(i).(fld));
            pos = i + off;
            fprintf(fid, '\\addplot+[boxplot prepared={draw direction=y, draw position=%.2f, box extend=0.30,', pos);
            fprintf(fid, ' lower whisker=%.5f, lower quartile=%.5f, median=%.5f,', ...
                tr(st.lw), tr(st.q1), tr(st.med));
            fprintf(fid, ' upper quartile=%.5f, upper whisker=%.5f}, %s', ...
                tr(st.q3), tr(st.uw), sty);
            fprintf(fid, ', forget plot] coordinates {');
            for o = 1:numel(st.out), fprintf(fid, '(0,%.5f) ', tr(st.out(o))); end
            fprintf(fid, '};\n');
        end
    end
    fclose(fid);
end

function st = bstats(x)
    x = x(:);
    st.q1  = prctile(x,25);  st.med = prctile(x,50);  st.q3 = prctile(x,75);
    iqr_   = st.q3 - st.q1;
    lof    = st.q1 - 1.5*iqr_;   upf = st.q3 + 1.5*iqr_;
    inl    = x(x >= lof & x <= upf);
    st.lw  = min(inl);  st.uw = max(inl);
    st.out = x(x < lof | x > upf);
end
